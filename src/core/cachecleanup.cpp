struct Handle {
    HANDLE h = INVALID_HANDLE_VALUE;
    explicit Handle(HANDLE value = INVALID_HANDLE_VALUE):h(value) {}
    ~Handle() { if (h != INVALID_HANDLE_VALUE) CloseHandle(h); }
    Handle(const Handle &) = delete;
    Handle &operator=(const Handle &) = delete;
};
using HandlePtr = std::shared_ptr<Handle>;
HandlePtr openPath(const QString &path, bool removeAccess) {
    const QString native = QDir::toNativeSeparators(path);
    // Denying FILE_SHARE_DELETE pins each ancestor against rename/replacement.
    auto h = std::make_shared<Handle>(CreateFileW(reinterpret_cast<LPCWSTR>(native.utf16()),
        FILE_READ_ATTRIBUTES | (removeAccess ? DELETE : 0), FILE_SHARE_READ | FILE_SHARE_WRITE,
        nullptr, OPEN_EXISTING, FILE_FLAG_BACKUP_SEMANTICS | FILE_FLAG_OPEN_REPARSE_POINT, nullptr));
    return h->h == INVALID_HANDLE_VALUE ? HandlePtr{} : h;
}
bool info(const HandlePtr &h, CleanupEntry &e) {
    BY_HANDLE_FILE_INFORMATION v{};
    if (!h || !GetFileInformationByHandle(h->h, &v) || (v.dwFileAttributes & FILE_ATTRIBUTE_REPARSE_POINT)) return false;
    e.directory = (v.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) != 0;
    if (!e.directory && v.nNumberOfLinks != 1) return false;
    e.volume = v.dwVolumeSerialNumber; e.index = (quint64(v.nFileIndexHigh)<<32)|v.nFileIndexLow;
    e.size = e.directory ? 0 : (quint64(v.nFileSizeHigh)<<32)|v.nFileSizeLow;
    e.modified = (quint64(v.ftLastWriteTime.dwHighDateTime)<<32)|v.ftLastWriteTime.dwLowDateTime;
    return true;
}
bool same(const CleanupEntry &a, const CleanupEntry &b) {
    return a.relative==b.relative && a.volume==b.volume && a.index==b.index && a.directory==b.directory &&
           a.size==b.size && a.modified==b.modified;
}
struct Pins { std::vector<HandlePtr> handles; CleanupEntry root; };
bool pinRoot(const QString &path, Pins &pins) {
    if (path.isEmpty() || !QDir::isAbsolutePath(path)) return false;
    const QString clean=QDir::cleanPath(path);
    if (clean!=QDir::fromNativeSeparators(path) || QDir(clean).isRoot()) return false;
    QStringList chain; QString part=clean;
    for (;;) {
        chain.prepend(part); const QString parent=QFileInfo(part).dir().absolutePath();
        if (parent==part) break;
        part=parent;
    }
    for (const auto &p:chain) {
        auto h=openPath(p,false); CleanupEntry e;
        if (!info(h,e) || !e.directory) return false;
        pins.handles.push_back(h); pins.root=e;
    }
    return true;
}
bool matchingRoot(const Pins &p, quint64 volume, quint64 index) { return p.root.volume==volume && p.root.index==index; }
// All paths here are generated by our own bounded traversal, never supplied by
// callers. Hold each directory handle while its descendants are inspected.
bool captureTree(const QString &root, const QString &rel, QList<CleanupEntry> &entries,
                 std::vector<HandlePtr> &held, int &budget, int depth, const CleanupCanceled &cancel) {
    if (stopped(cancel) || depth>MaxDepth || budget<=0) return false;
    auto h=openPath(QDir(root).filePath(rel), true); CleanupEntry entry; entry.relative=rel;
    if (!info(h,entry)) return false;
    --budget; entries.append(entry); held.push_back(h);
    if (!entry.directory) return true;
    QDirIterator it(QDir(root).filePath(rel), QDir::AllEntries|QDir::Hidden|QDir::System|QDir::NoDotAndDotDot);
    while (it.hasNext()) {
        if (stopped(cancel) || budget<=0) return false;
        it.next(); const QString name=it.fileName();
        if (!captureTree(root, rel+QLatin1Char('/')+name, entries, held, budget, depth+1, cancel)) return false;
    }
    return true;
}
bool sameTree(QList<CleanupEntry> a, QList<CleanupEntry> b) {
    auto less=[](const CleanupEntry &x,const CleanupEntry &y){return x.relative<y.relative;};
    std::sort(a.begin(),a.end(),less); std::sort(b.begin(),b.end(),less);
    if(a.size()!=b.size()) return false;
    for(qsizetype i=0;i<a.size();++i) if(!same(a[i],b[i])) return false;
    return true;
}
bool removeHandle(const HandlePtr &h) {
    FILE_DISPOSITION_INFO disposition{}; disposition.DeleteFile=TRUE;
    return SetFileInformationByHandle(h->h, FileDispositionInfo, &disposition, sizeof(disposition)) != 0;
}
