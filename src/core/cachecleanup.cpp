CleanupPlan planCacheCleanup(const QString &dataRoot,const QString &logRoot,const QSet<QString> &protectedTokens,const CleanupCanceled &cancel,bool preserveCurrentLog,bool preserveRotatingLogs) {
    CleanupPlan out; out.dataRoot=dataRoot; out.logRoot=logRoot;
#ifdef Q_OS_WIN
    Pins logs;
    if (pinRoot(logRoot,logs)) {
        out.logVolume=logs.root.volume; out.logIndex=logs.root.index;
        auto names=logNames();
        if(preserveRotatingLogs) {names.removeAll(QStringLiteral("diagnostic.1.jsonl"));names.removeAll(QStringLiteral("diagnostic.2.jsonl"));}
        if(!preserveCurrentLog)names.prepend(QStringLiteral("diagnostic.jsonl"));
        for (const auto &name:names) {
            if(stopped(cancel)){out.canceled=true;return out;}
            const QString path=QDir(logRoot).filePath(name);
            if (!QFileInfo::exists(path) && !QFileInfo(path).isSymLink()) continue;
            auto h=openPath(path,true); CleanupEntry e; e.relative=name;
            if(!info(h,e)||e.directory){++out.skipped;continue;}
            out.logs.append(e);out.bytes+=e.size;++out.items;
        }
    } else if (QFileInfo::exists(logRoot)) { ++out.failures;out.partial=true; }
    Pins data;
    if (!pinRoot(dataRoot,data)) { if(QFileInfo::exists(dataRoot)){++out.failures;out.partial=true;} return out; }
    out.dataVolume=data.root.volume;out.dataIndex=data.root.index;
    const QString spool=QDir(dataRoot).filePath(QStringLiteral("clipboard-spool"));
    if (!QFileInfo::exists(spool) && !QFileInfo(spool).isSymLink()) return out;
    auto spoolHandle=openPath(spool,false); CleanupEntry spoolInfo;
    if(!info(spoolHandle,spoolInfo)||!spoolInfo.directory){++out.failures;out.partial=true;return out;}
    QDirIterator it(spool,QDir::AllEntries|QDir::Hidden|QDir::System|QDir::NoDotAndDotDot);
    int budget=MaxEntries;
    while(it.hasNext()) {
        if(stopped(cancel)){out.canceled=true;return out;}
        if(--budget<0){out.partial=true;break;}
        it.next();const QString name=it.fileName();
        if(!isCleanupToken(name)) continue;
        if(protectedTokens.contains(name)){++out.skipped;continue;}
        const QFileInfo lockInfo(QDir(spool).filePath(name+QStringLiteral(".lock")));
        if(lockInfo.isSymLink()||lockInfo.isJunction()){++out.skipped;continue;}
        QLockFile lock(lockInfo.absoluteFilePath()); if(!lock.tryLock(0)){++out.skipped;continue;}
        CleanupBatch batch; batch.token=name; std::vector<HandlePtr> held;
        if(!captureTree(spool,name,batch.entries,held,budget,0,cancel) || batch.entries.isEmpty() || !batch.entries.first().directory) {
            ++out.skipped;out.partial=true;continue;
        }
        for(const auto &e:batch.entries){out.bytes+=e.size;if(!e.directory)++out.items;}
        out.batches.append(batch);
    }
#else
    Q_UNUSED(protectedTokens);Q_UNUSED(cancel);Q_UNUSED(preserveCurrentLog);Q_UNUSED(preserveRotatingLogs);
    // Fail closed until handle-relative deletion is implemented on this platform.
    out.partial=true;out.failures=1;out.supported=false;
#endif
    return out;
}
CleanupResult executeCacheCleanup(const CleanupPlan &plan,const QSet<QString> &protectedTokens,const CleanupCanceled &cancel) {
    CleanupResult out;out.skipped=plan.skipped;out.failures=plan.failures;out.partial=plan.partial;
#ifdef Q_OS_WIN
    Pins logs;
    if(!plan.logs.isEmpty() && (!pinRoot(plan.logRoot,logs)||!matchingRoot(logs,plan.logVolume,plan.logIndex))) {out.failures+=int(plan.logs.size());out.partial=true;}
    else for(const auto &old:plan.logs) {
        if(stopped(cancel)){out.canceled=true;return out;}
        if(old.relative!=QStringLiteral("diagnostic.jsonl")&&!logNames().contains(old.relative)){++out.failures;continue;}
        auto h=openPath(QDir(plan.logRoot).filePath(old.relative),true); CleanupEntry now;now.relative=old.relative;
        if(!info(h,now)||!same(old,now)){++out.skipped;continue;}
        if(stopped(cancel)){out.canceled=true;return out;}
        if(!removeHandle(h)){++out.skipped;continue;}
        out.bytes+=now.size;++out.items;
    }
    if(plan.batches.isEmpty()) return out;
    Pins data;
    if(!pinRoot(plan.dataRoot,data)||!matchingRoot(data,plan.dataVolume,plan.dataIndex)){out.failures+=int(plan.batches.size());out.partial=true;return out;}
    const QString spool=QDir(plan.dataRoot).filePath(QStringLiteral("clipboard-spool"));
    auto spoolHandle=openPath(spool,false);CleanupEntry si;
    if(!info(spoolHandle,si)||!si.directory){out.failures+=int(plan.batches.size());out.partial=true;return out;}
    int budget=MaxEntries;
    for(const auto &batch:plan.batches) {
        if(stopped(cancel)){out.canceled=true;break;}
        if(!isCleanupToken(batch.token)||protectedTokens.contains(batch.token)){++out.skipped;continue;}
        const QFileInfo lockInfo(QDir(spool).filePath(batch.token+QStringLiteral(".lock")));
        if(lockInfo.isSymLink()||lockInfo.isJunction()){++out.skipped;continue;}
        QLockFile lock(lockInfo.absoluteFilePath());if(!lock.tryLock(0)){++out.skipped;continue;}
        QList<CleanupEntry> current;std::vector<HandlePtr> held;
        if(!captureTree(spool,batch.token,current,held,budget,0,cancel)||!sameTree(batch.entries,current)) {++out.skipped;out.partial=true;continue;}
        // Children were opened after their parents. Delete in reverse order.
        for(qsizetype i=current.size();i>0;--i) {
            if(stopped(cancel)){out.canceled=true;break;}
            const auto &e=current[i-1];CleanupEntry latest;latest.relative=e.relative;
            if(!info(held[size_t(i-1)],latest)||(!e.directory&&!same(e,latest))){++out.failures;out.partial=true;continue;}
            if(stopped(cancel)){out.canceled=true;break;}
            if(!removeHandle(held[size_t(i-1)])){++out.failures;out.partial=true;continue;}
            if(!e.directory){out.bytes+=e.size;++out.items;}
            held[size_t(i-1)].reset();
        }
        if(out.canceled) break;
    }
#else
    Q_UNUSED(plan);Q_UNUSED(protectedTokens);Q_UNUSED(cancel);
#endif
    return out;
}
