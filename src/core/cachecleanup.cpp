constexpr int MaxEntries = 4096, MaxDepth = 24;
bool stopped(const CleanupCanceled &f) { return f && f(); }
QStringList logNames() {
    QStringList names{QStringLiteral("diagnostic.1.jsonl"), QStringLiteral("diagnostic.2.jsonl")};
    for (int i=0;i<16;++i) for (const auto prefix : {"crash-", "exit-"})
        names << QString::fromLatin1(prefix)+QStringLiteral("%1.log").arg(i,2,10,QLatin1Char('0'));
    return names;
}
