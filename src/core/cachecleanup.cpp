bool isCleanupToken(const QString &s) {
    static const QRegularExpression rx(QStringLiteral("^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"));
    return rx.match(s).hasMatch();
}
